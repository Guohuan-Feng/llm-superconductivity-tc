def safe(path):
    path = Path(path)
    for parent in (path, *path.parents):
        if parent.exists() and (parent.is_symlink() or parent.is_junction()):
            raise ValueError(f'Linked destination: {parent}')
    resolved = path.resolve()
    if any('onedrive' in part.lower() for part in resolved.parts):
        raise ValueError('OneDrive destination rejected')
    resolved.relative_to(ROOT.resolve())
    return resolved


def inline(value):
    value = html.escape(value)
    value = re.sub(r'`([^`]+)`', r'<code>\1</code>', value)
    return re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', value)


def markdown_tables(source):
    """Render the deliberately simple headings/tables generated by our reporters."""
    lines, out = source.splitlines(), []
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            i += 1
            continue
        heading = re.match(r'^(#{1,6})\s+(.+)$', line)
        if heading:
            level = min(6, len(heading[1]) + 1)
            out.append(f'<h{level}>{inline(heading[2])}</h{level}>')
        elif line.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                cells = [v.strip() for v in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-{3,}:?', v) for v in cells):
                    rows.append(cells)
                i += 1
            out.append('<div class="scroll"><table><thead><tr>' + ''.join('<th>'+inline(c)+'</th>' for c in rows[0]) + '</tr></thead><tbody>')
            out.extend('<tr>'+''.join('<td>'+inline(c)+'</td>' for c in row)+'</tr>' for row in rows[1:])
            out.append('</tbody></table></div>')
            continue
        else:
            out.append('<p>'+inline(line)+'</p>')
        i += 1
    return '\n'.join(out)


def table(headers, rows):
    return '<div class="scroll"><table><thead><tr>' + ''.join('<th>'+inline(str(c))+'</th>' for c in headers) + '</tr></thead><tbody>' + ''.join('<tr>'+''.join('<td>'+inline(str(c))+'</td>' for c in row)+'</tr>' for row in rows) + '</tbody></table></div>'


def interval(value):
    if value['point'] is None:
        rendered = 'NA'
    else:
        low, high = value['ci95']
        rendered = f'{100*value["point"]:.2f}'
        rendered += f' [{100*low:.2f}, {100*high:.2f}]' if low is not None else ' [NA]'
    if value.get('n_undefined_boot', 0):
        rendered += f' (有效 {value["n_valid_boot"]}/5000)'
    return rendered


def g2_full_tables(metrics):
    """Expose all already-computed strata and paired CIs, with no new statistics."""
    output = ['<p>数值为百分比或百分点及 95% CI；Brier 也乘 100 显示。所有区间来自已有的 5000 次共享组抽样。ECE/Brier 越低越好；配对差始终为 arm_a − arm_b。</p>',
              '<p>每次组重采样均重新排序、确定 top-k 和覆盖率边界。并列桶按分数选择，不依赖标签或 ID；加权 precision 是分数计数之比，不是随机打破并列后比值的期望。k 和覆盖率目标均按材料数定义；各权重下的实际覆盖率另列。概率不做重新校准。</p>']
    collections = [('主比较', metrics['subsets'])]
    collections += [('家族/'+name, value) for name, value in metrics['families'].items()]
    collections += [('原组大小/'+name, value) for name, value in metrics['group_size_bins'].items()]
    for name, subsets in collections:
        for subset, result in subsets.items():
            opened = ' open' if name == '主比较' and subset != 'only_93' else ''
            output.append(f'<details{opened}><summary>{inline(name+" / "+subset)} · n={result["n"]}, groups={result["n_groups"]}, positive={result["n_positive"]}</summary>')
            for warning in ('single_group_warning', 'empty_warning'):
                if result.get(warning):
                    output.append('<p>'+inline(result[warning])+'</p>')
            if not result['methods']:
                output.append('</details>')
                continue
            rows, boundaries = [], []
            for method, value in result['methods'].items():
                highest = max(value['probability_value_counts'], key=lambda v: v['p'])
                rows.append([method, value['n_unique_probabilities'], value['largest_probability_tie_n'], highest['p'], highest['n']])
                for k, boundary in value['top_k_boundaries'].items():
                    boundaries.append([method, k, *([boundary['boundary_score'], boundary['boundary_tie_n'], boundary['selected_boundary_fraction']] if boundary['defined'] else ['NA']*3)])
            output.append(table(['方法', 'p取值数', '最大并列桶n', '最高p', '最高p并列n'], rows))
            output.append('<details><summary>top-k 边界与并列选择</summary>'+table(['方法', 'k', '边界p', '边界并列n', '所选比例'], boundaries)+'</details>')
            for weighting in ('group_weighted', 'unweighted'):
                output.append('<h4>'+weighting+'</h4>')
                rows, ranking, selective, calibration = [], [], [], []
                for method, value in result['methods'].items():
                    scheme = value[weighting]
                    rows.append([method]+[interval(scheme['classification'][key]) for key in ('balanced_accuracy', 'precision', 'recall', 'accuracy')])
                    ranking.append([method]+[interval(scheme['precision_at_k'][str(k)]['precision']) for k in (50,100,200,500)]+[interval(scheme['calibration'][key]) for key in ('ece', 'brier')])
                    for q, point in scheme['selective'].items():
                        selective.append([method, q, interval(point['weighted_coverage']), interval(point['accuracy'])])
                    for b in scheme['calibration']['bins']:
                        calibration.append([method, f'[{b["lower"]:.1f}, {b["upper"]:.1f}'+(']' if b['upper_inclusive'] else ')'), *[interval(b[key]) for key in ('weight_fraction', 'mean_p', 'positive_fraction')]])
                output.append(table(['方法', 'BA', '精确率', '召回率', '准确率'], rows))
                output.append(table(['方法', 'P@50', 'P@100', 'P@200', 'P@500', 'ECE', 'Brier×100'], ranking))
                output.append('<details><summary>选择性预测全部覆盖率点</summary>'+table(['方法', '目标材料覆盖率', '该权重实际覆盖率', '保留材料准确率'], selective)+'</details>')
                output.append('<details><summary>校准分箱与置信区间</summary>'+table(['方法', '概率区间', '权重占比', '平均p', '正类比例'], calibration)+'</details>')
                paired = []
                for pair in result['paired_differences'].values():
                    for metric, value in pair[weighting].items():
                        paired.append([pair['arm_a'], pair['arm_b'], metric, interval(value)])
                output.append('<details><summary>全部配对差值与置信区间</summary>'+table(['arm_a', 'arm_b', '指标', '差值（百分点）'], paired)+'</details>')
            output.append('</details>')
    return '\n'.join(output)


def projection_tables(metrics):
    output = ['<details><summary>CHGNet 主占位投影：未改变 / 改变子集</summary><p>这些子集沿用全训练折拟合的同一模型，没有单独重训；均为开发数据，且全部仍为 proxy cell。原组权重保留。</p>']
    for name, subsets in metrics['CHGNet_projection_subsets'].items():
        for subset, result in subsets.items():
            output.append(f'<h4>{inline(name+" / "+subset)} · n={result["n"]}, groups={result["n_groups"]}, positive={result["n_positive"]}</h4>')
            for weighting in ('group_weighted', 'unweighted'):
                scheme = result[weighting]
                output.append('<p>'+weighting+'</p>')
                output.append(table(['方法', 'BA', '精确率', '召回率', '准确率'], [[method]+[interval(values[key]) for key in ('balanced_accuracy','precision','recall','accuracy')] for method, values in scheme['metrics'].items()]))
                rows = [[pair['arm_a'], pair['arm_b']]+[interval(pair[key]) for key in ('balanced_accuracy','precision','recall','accuracy')] for pair in scheme['paired_differences'].values()]
                output.append('<details><summary>配对差（百分点）</summary>'+table(['arm_a','arm_b','BA','精确率','召回率','准确率'], rows)+'</details>')
    return '\n'.join(output)+'</details>'


def main_overview():
    g1 = json.loads((ROOT/'G1_structure_baselines/metrics.json').read_text(encoding='utf-8'))['classification']
    g3 = json.loads((ROOT/'G3_complementarity/metrics.json').read_text(encoding='utf-8'))
    methods = [(name, g3) for name in ('A3', 'A2', 'HGB127', 'StrongML')]
    methods += [(name, g1) for name in ('CGCNN_scratch', 'CHGNet_dominant_HGB', 'CHGNet_dominant_LR', 'Magpie_RF')]
    methods += [(name, g3) for name in ('G3_stacked_LR', 'G3_simple_mean', 'G3_HGB_plus_family')]
    output = ['<h2>主结果总表</h2><p>BA、精确率、召回率、准确率均为 % [95% CI]。G1 候选的抽样 seed=20261016，其余为 20261018；配对差使用各实验内部共享抽样，见下方原始实验表。此处只汇集各方法已有区间，没有重新拟合或跨实验拼接抽样。</p>']
    for subset, label in [('all', '全部'), ('exclude_93', '去掉 component 93'), ('only_93', '仅 component 93')]:
        cohort = g3['subsets'][subset]
        output.append(f'<details'+(' open' if subset == 'all' else '')+f'><summary>{label} · n={cohort["n"]} / {cohort["n_groups"]} 组 / 正类 {cohort["n_positive"]}</summary>')
        for weighting, scheme in [('group_weighted', '组加权'), ('unweighted', '不加权')]:
            output.append('<h3>'+scheme+'</h3>')
            rows = []
            for name, source in methods:
                values = source['subsets'][subset][weighting]['metrics'][name]
                rows.append([name]+[interval(values[key]) for key in ('balanced_accuracy', 'precision', 'recall', 'accuracy')])
            output.append(table(['方法', 'BA', '精确率', '召回率', '准确率'], rows))
        output.append('</details>')
    return '\n'.join(output)


